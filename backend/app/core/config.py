from functools import lru_cache
from pathlib import Path
import os

from pydantic_settings import BaseSettings, SettingsConfigDict
from pydantic import Field, SecretStr


PROJECT_ROOT = Path(__file__).resolve().parents[3]


class Settings(BaseSettings):
    hpc_admin_token: SecretStr | None = None
    hpc_experiment_root: str = str(PROJECT_ROOT / "backend" / "artifacts" / "experiments")
    hpc_enabled: bool = True
    hpc_max_workers: int = Field(default_factory=lambda: min(8, max(1, (os.cpu_count() or 1) - 1)), ge=1, le=8)
    hpc_timeout_seconds: float = Field(default=30, ge=1, le=120)
    hpc_queue_timeout_seconds: float = Field(default=10, ge=0.1, le=60)
    hpc_max_pending: int = Field(default=8, ge=1, le=64)
    hpc_auto_min_candidates: int = Field(default=256, ge=1)
    database_url: str | None = None
    razorpay_key_id: str | None = None
    razorpay_key_secret: str | None = None
    razorpay_webhook_secret: SecretStr | None = None
    # Deliberately narrow merchant HTTP boundary. This value is never exposed
    # to the shopper application or commerce-domain services.
    merchant_admin_token: SecretStr | None = None
    # Supabase Auth is the production identity provider.  The backend only
    # needs the project URL to discover public JWKS keys; the publishable key
    # is used only when a legacy HS256 project must ask Auth to validate a
    # token. Neither value is frontend configuration generated by this API.
    supabase_url: str | None = None
    supabase_publishable_key: SecretStr | None = None
    legacy_merchant_auth_enabled: bool = False
    anonymous_session_ttl_hours: int = Field(default=168, ge=1, le=24 * 31)
    # Local-first multilingual speech remains opt-in.  By default the
    # pretrained model identifier is resolved through faster-whisper's normal
    # cache/download lifecycle.  VOICE_MODEL_PATH is an optional deployment
    # override for an already staged converted model directory.
    voice_commerce_enabled: bool = False
    voice_model: str = "base"
    voice_model_path: str | None = None
    voice_device: str = "cpu"
    voice_compute_type: str = "int8"
    voice_max_seconds: int = Field(default=45, ge=1, le=120)
    voice_max_bytes: int = Field(default=8_000_000, ge=32_768, le=32_000_000)
    voice_max_concurrent: int = Field(default=1, ge=1, le=4)
    # Optional, provider-neutral Agentic Intent Intelligence configuration.
    # Disabled by default so normal startup and tests never require a provider.
    ai_intent_enabled: bool = False
    ai_base_url: str | None = None
    ai_api_key: str | None = None
    ai_model: str | None = None
    ai_timeout_seconds: float = Field(default=3.0, ge=0.1, le=10.0)
    ai_assist_max_calls_per_hour: int = Field(default=12, ge=0, le=100)
    # Optional bounded dense retrieval.  It is deliberately off by default:
    # normal development, tests and an unavailable local model keep the
    # deterministic relevance path intact.
    semantic_retrieval_enabled: bool = False
    semantic_retrieval_model: str = "sentence-transformers/all-MiniLM-L6-v2"
    semantic_retrieval_candidate_k: int = 12
    semantic_retrieval_local_files_only: bool = True
    # Comma-delimited so deployment env files remain easy to inspect; unlike a
    # list setting this does not require JSON escaping in a platform dashboard.
    frontend_allowed_origins: str = "http://localhost:3000,http://127.0.0.1:3000,http://localhost:3100,http://127.0.0.1:3100"

    model_config = SettingsConfigDict(
        env_file=PROJECT_ROOT / ".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    @property
    def cors_allowed_origins(self) -> list[str]:
        return [origin.strip().rstrip("/") for origin in self.frontend_allowed_origins.split(",") if origin.strip()]

    @property
    def supabase_auth_issuer(self) -> str | None:
        return f"{self.supabase_url.rstrip('/')}/auth/v1" if self.supabase_url else None

    @property
    def voice_model_source(self) -> str:
        """Return the operator override when present, otherwise the pretrained id."""
        return self.voice_model_path or self.voice_model

    @property
    def voice_uses_local_path_override(self) -> bool:
        return bool(self.voice_model_path and Path(self.voice_model_path).is_dir())


@lru_cache
def get_settings() -> Settings:
    return Settings()
